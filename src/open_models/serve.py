"""Serve the working-store models over the network with llama.cpp's `llama-server` (Stage 5b).

Summary: builds everything `om serve` and `om service` need: a model presets file
generated from the catalog, the llama-server router-mode command line, and the macOS
launchd agent that runs `om serve` at login. The CLI (`cli.py`) calls these and does the
actual exec / launchctl calls. docs/SERVING.md explains the choice of llama-server over
Ollama and how to use the chat page from another computer.

Details:
- Router mode: one `llama-server` process (the router) lists every preset model and
  starts a child llama-server for the model a request names, unloading the least recently
  used one beyond `models_max`. With `--sleep-idle-seconds` a model is also unloaded after
  that long without requests and reloaded on the next one.
- Presets (`presets_ini`): an INI file, one `[<catalog id>]` section per model that is
  complete on the given store (`Store.status == PRESENT`) and in GGUF format. Each section
  gives `model` (absolute path of the first model .gguf, so shard 00001 for split models),
  `mmproj` (the vision adapter, if the model has a file starting with "mmproj"), and
  `embeddings = true` for `role: embedding`, since llama-server refuses embedding
  requests without it. The `[*]` section sets the context size for all models.
  Format: llama.cpp tools/server/README.md, "Model presets" (build 12359).
- Not handled: other per-model flags from the catalog notes (e.g. DeepSeek V4.1 Flash's
  `--ple`), because only working-store models are served and none needs one.
- Files outside the repo, under `config_dir()` (default `~/.config/open-models`, override
  `OPEN_MODELS_CONFIG`): the API key (`llama-server.key`, created on first use, mode 600)
  and the generated `presets.ini` (rewritten on every `om serve`).
- launchd (`launch_agent`): a per-user agent `com.open-models.serve` that runs this venv's
  `om serve ...` at login, restarts it if it exits (e.g. the working store is not mounted
  yet; it retries every THROTTLE_SECONDS), and logs to `~/Library/Logs/open-models/serve.log`.
"""

import os
import secrets
from pathlib import Path

from .catalog import Model
from .store import PRESENT, Store

LABEL = "com.open-models.serve"
THROTTLE_SECONDS = 30
# launchd starts agents with a minimal PATH; Homebrew's bin holds llama-server.
LAUNCHD_PATH = "/opt/homebrew/bin:/usr/local/bin:/usr/bin:/bin:/usr/sbin:/sbin"
# Environment settings passed through to the agent if set when it is installed.
PASSTHROUGH_ENV = ("OPEN_MODELS_ARCHIVE", "OPEN_MODELS_WORKING", "OPEN_MODELS_CONFIG", "LLAMA_SERVER")


def config_dir() -> Path:
    """Folder for the API key and generated presets: `$OPEN_MODELS_CONFIG` or ~/.config/open-models."""
    return Path(os.environ.get("OPEN_MODELS_CONFIG", Path.home() / ".config" / "open-models"))


def main_gguf(model: Model) -> str | None:
    """Relative path of the file llama.cpp should load: the first model .gguf, skipping mmproj.

    For split models this is shard 00001; llama.cpp finds the other shards itself. Returns
    None if the model has no model .gguf (e.g. a safetensors entry). Also used by `om path`.
    """
    ggufs = sorted(f.path for f in model.files
                   if f.path.endswith(".gguf") and "mmproj" not in f.path.lower())
    return ggufs[0] if ggufs else None


def mmproj_file(model: Model) -> str | None:
    """Relative path of the model's vision adapter (a .gguf whose name starts with "mmproj"), or None."""
    for f in sorted(model.files, key=lambda f: f.path):
        name = Path(f.path).name.lower()
        if name.startswith("mmproj") and name.endswith(".gguf"):
            return f.path
    return None


def served_models(models: dict[str, Model], store: Store) -> list[Model]:
    """The catalog models the server offers: GGUF, with a model file, complete on `store`."""
    return [m for m in models.values()
            if m.format == "gguf" and main_gguf(m) and store.status(m) == PRESENT]


def presets_ini(models: list[Model], store: Store, ctx: int) -> str:
    """Return the llama-server presets file text for `models` (all assumed present on `store`)."""
    lines = ["; Generated by `om serve` from catalog/models.yaml. Do not edit: it is rewritten",
             "; on every start. Format: llama.cpp tools/server/README.md, \"Model presets\".",
             "version = 1", "", "[*]", f"c = {ctx}", ""]
    for m in models:
        d = store.model_dir(m)
        lines += [f"[{m.id}]", f"model = {d / main_gguf(m)}"]
        if mm := mmproj_file(m):
            lines.append(f"mmproj = {d / mm}")
        if m.role == "embedding":
            lines.append("embeddings = true")
        lines.append("")
    return "\n".join(lines)


def ensure_key(path: Path) -> bool:
    """Create a random API key at `path` (readable only by the owner) if missing; True if created."""
    if path.is_file() and path.read_text().strip():
        return False
    path.parent.mkdir(parents=True, exist_ok=True)
    fd = os.open(path, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
    with os.fdopen(fd, "w") as fh:
        fh.write(secrets.token_urlsafe(24) + "\n")
    return True


def server_command(presets: Path, key_file: Path, host: str, port: int, models_max: int,
                   idle_seconds: int) -> list[str]:
    """The llama-server router-mode command line (`$LLAMA_SERVER`, default from PATH)."""
    cmd = [os.environ.get("LLAMA_SERVER", "llama-server"), "--models-preset", str(presets),
           "--models-max", str(models_max), "--host", host, "--port", str(port),
           "--api-key-file", str(key_file)]
    if idle_seconds > 0:
        cmd += ["--sleep-idle-seconds", str(idle_seconds)]
    return cmd


def launch_agent(om: Path, serve_args: list[str], log: Path) -> dict:
    """The launchd agent definition (for plistlib) that runs `om serve <serve_args>` at login.

    `RunAtLoad` starts it at login (and when installed); `KeepAlive` restarts it whenever
    it exits, at most every THROTTLE_SECONDS, so it waits out an unmounted working store.
    """
    env = {"PATH": LAUNCHD_PATH}
    env |= {k: os.environ[k] for k in PASSTHROUGH_ENV if k in os.environ}
    return {
        "Label": LABEL,
        "ProgramArguments": [str(om), "serve", *serve_args],
        "RunAtLoad": True,
        "KeepAlive": True,
        "ThrottleInterval": THROTTLE_SECONDS,
        "EnvironmentVariables": env,
        "StandardOutPath": str(log),
        "StandardErrorPath": str(log),
    }
